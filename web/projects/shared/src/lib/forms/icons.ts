/** Every offered icon once, in group order. */
export const ALL_ICONS: string[] = [...new Set(ICON_GROUPS.flatMap((g) => g.icons))];

/** Icons whose name contains every word of the search ("event permit" finds `event`, …). */
export function searchIcons(term: string, icons: readonly string[] = ALL_ICONS): string[] {
  const words = term
    .trim()
    .toLowerCase()
    .replace(/[_-]+/g, ' ')
    .split(/\s+/)
    .filter((w) => w);
  if (!words.length) return [...icons];
  return icons.filter((icon) => words.every((w) => icon.replace(/_/g, ' ').includes(w)));
}

/** A plausible Material Symbols name: lower-case letters, digits and underscores. */
export const ICON_NAME = /^[a-z0-9_]{1,40}$/;
